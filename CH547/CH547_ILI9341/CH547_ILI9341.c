void ili9341_init(void)
{
	gpio_clear_pin(ILI9341_PORT_RST, ILI9341_PIN_RST);
	rcc_delay_us(10);
	gpio_set_pin(ILI9341_PORT_RST, ILI9341_PIN_RST);
	ili9341_cs_release();
	spi_init(ILI9341_SPI_CLK_DIV, SPI_MODE_3);
	rcc_delay_ms(120);
	
	ili9341_write_command(0xEF);	//undocumented mystery command
	ili9341_write_data_single(0x03);
	ili9341_write_data_single(0x80);
	ili9341_write_data_single(0x02);
	
	ili9341_write_command(ILI9341_COM_POWER_CONTROL_B);
	ili9341_write_data_single(0x00);
	ili9341_write_data_single(0xBA);
	ili9341_write_data_single(0xB0);
	
	ili9341_write_command(ILI9341_COM_POWER_ON_SEQ_CTRL);
	ili9341_write_data_single(0x67);
	ili9341_write_data_single(0x03);
	ili9341_write_data_single(0x12);
	ili9341_write_data_single(0x81);
	
	ili9341_write_command(ILI9341_COM_DRV_TIMING_CTRL_A);
	ili9341_write_data_single(0x85);
	ili9341_write_data_single(0x11);
	ili9341_write_data_single(0x79);
	
	ili9341_write_command(ILI9341_COM_POWER_CONTROL_A);
	ili9341_write_data_single(0x39);
	ili9341_write_data_single(0x2C);
	ili9341_write_data_single(0x00);
	ili9341_write_data_single(0x34);
	ili9341_write_data_single(0x06);
	
	ili9341_write_command(ILI9341_COM_PUMP_RATIO_CTRL);
	ili9341_write_data_single(0x20);
	
	ili9341_write_command(ILI9341_COM_DRV_TIMING_CTRL_B);
	ili9341_write_data_single(0x00);
	ili9341_write_data_single(0x00);
	
	ili9341_write_command(ILI9341_COM_POWER_CONTROL_1);
	ili9341_write_data_single(0x1D);
	
	ili9341_write_command(ILI9341_COM_POWER_CONTROL_2);
	ili9341_write_data_single(0x12);
	
	ili9341_write_command(ILI9341_COM_VCOM_CONTROL_1);
	ili9341_write_data_single(0x44);
	ili9341_write_data_single(0x3C);
	
	ili9341_write_command(ILI9341_COM_VCOM_CONTROL_2);
	ili9341_write_data_single(0x9E);
	
	ili9341_write_command(ILI9341_COM_COLMOD_PIX_FMT_SET);
	ili9341_write_data_single(0x55);	//16 bit per pixel
	
	ili9341_write_command(ILI9341_COM_MEM_ACCESS_CTRL);
	ili9341_write_data_single(ILI9341_DEF_MEM_ACCESS_CTRL);
	
	ili9341_write_command(ILI9341_COM_FRAME_RATE_CTRL_N);
	ili9341_write_data_single(0x00);
	ili9341_write_data_single(0x17);
	
	ili9341_write_command(ILI9341_COM_DISP_FUNCTION_CTRL);
	ili9341_write_data_single(0x0A);
	ili9341_write_data_single(0xA2);
	ili9341_write_data_single(0x27);	//not in original startup sequence
	ili9341_write_data_single(0x09);	//not in original startup sequence
	
	ili9341_write_command(ILI9341_COM_ENABLE_3G);
	ili9341_write_data_single(0x02);
	
	ili9341_write_command(ILI9341_COM_GAMMA_SET);
	ili9341_write_data_single(0x01);
	
	ili9341_write_command(ILI9341_COM_POS_GAMMA_CORRECT);
	ili9341_write_data(ili9341_pos_gamma_tab, 15);
	
	ili9341_write_command(ILI9341_COM_NEG_GAMMA_CORRECT);
	ili9341_write_data(ili9341_neg_gamma_tab, 15);
	
	ili9341_write_command(ILI9341_COM_SLEEP_OUT);
	rcc_delay_ms(60);
	
	ili9341_write_command(ILI9341_COM_DISPLAY_ON);
	
	ili9341_fill_color = 0xF81F;
	ili9341_fill_display();
}

void ili9341_write_command(UINT8 command)
{
	ili9341_enter_command_mode();
	ili9341_cs_assert();
	(void)spi_transfer(command);
	ili9341_cs_release();
}

void ili9341_write_data_single(UINT8 val)
{
	ili9341_enter_data_mode();
	ili9341_cs_assert();
	(void)spi_transfer(val);
	ili9341_cs_release();
}

void ili9341_write_data(UINT8* src, UINT16 len)
{
	ili9341_enter_data_mode();
	ili9341_cs_assert();
	(void)spi_bulk_out(src, len);
	ili9341_cs_release();
}

UINT8 ili9341_read_data_single(void)
{
	UINT8 temp;
	ili9341_enter_data_mode();
	ili9341_cs_assert();
	temp = spi_transfer(0x00);
	ili9341_cs_release();
	return temp;
}

void ili9341_read_data(UINT8* dest, UINT16 len)
{
	ili9341_enter_data_mode();
	ili9341_cs_assert();
	(void)spi_bulk_in(dest, 0x00, len);
	ili9341_cs_release();
}

void ili9341_write_gram_single(UINT16 val)
{
	ili9341_enter_data_mode();
	ili9341_cs_assert();
	(void)spi_transfer((UINT8)(val >> 8));
	(void)spi_transfer((UINT8)val);
	ili9341_cs_release();
}

void ili9341_write_gram(UINT16* src, UINT16 len)
{
	ili9341_enter_data_mode();
	ili9341_cs_assert();
	(void)spi_bulk_out((UINT8*)src, len << 1);
	ili9341_cs_release();
}

UINT16 ili9341_read_gram_single(void)
{
	UINT16 temp;
	ili9341_enter_data_mode();
	ili9341_cs_assert();
	temp = spi_transfer(0x00);
	temp <<= 8;
	temp |= spi_transfer(0x00);
	ili9341_cs_release();
	return temp;
}

void ili9341_read_gram(UINT16* dest, UINT16 len)
{
	ili9341_enter_data_mode();
	ili9341_cs_assert();
	(void)spi_bulk_in((UINT8*)dest, 0x00, len << 1);
	ili9341_cs_release();
}

void ili9341_set_gram_window(UINT16 row, UINT16 col, UINT16 width, UINT16 height)
{
	ili9341_write_command(ILI9341_COM_COLUMN_ADDRESS_SET);
	ili9341_write_data_single((UINT8)(col >> 8));
	ili9341_write_data_single((UINT8)col);
	col += width - 1;
	ili9341_write_data_single((UINT8)(col >> 8));
	ili9341_write_data_single((UINT8)col);

	ili9341_write_command(ILI9341_COM_PAGE_ADDRESS_SET);
	ili9341_write_data_single((UINT8)(row >> 8));
	ili9341_write_data_single((UINT8)row);
	row += height - 1;
	ili9341_write_data_single((UINT8)(row >> 8));
	ili9341_write_data_single((UINT8)row);
	
	ili9341_write_command(ILI9341_COM_MEMORY_WRITE);
}

void ili9341_set_pixel(UINT16 row, UINT16 col, UINT16 color)
{
	ili9341_write_command(ILI9341_COM_COLUMN_ADDRESS_SET);
	ili9341_write_data_single((UINT8)(col >> 8));
	ili9341_write_data_single((UINT8)col);
	ili9341_write_data_single((UINT8)(col >> 8));
	ili9341_write_data_single((UINT8)col);

	ili9341_write_command(ILI9341_COM_PAGE_ADDRESS_SET);
	ili9341_write_data_single((UINT8)(row >> 8));
	ili9341_write_data_single((UINT8)row);
	ili9341_write_data_single((UINT8)(row >> 8));
	ili9341_write_data_single((UINT8)row);
	
	ili9341_write_command(ILI9341_COM_MEMORY_WRITE);
	
	ili9341_enter_data_mode();
	ili9341_cs_assert();
	(void)spi_transfer((UINT8)(color >> 8));
	(void)spi_transfer((UINT8)color);
	ili9341_cs_release();
}

void ili9341_fill_rectangle(UINT16 row, UINT16 col, UINT16 width, UINT16 height)
{
	UINT32 num_pixels;
	
	num_pixels = (UINT32)width * (UINT32)height;
	ili9341_set_gram_window(row, col, width, height);
	ili9341_enter_data_mode();
	ili9341_cs_assert();
	while(num_pixels--)
	{
		(void)spi_transfer((UINT8)(ili9341_fill_color >> 8));
		(void)spi_transfer((UINT8)ili9341_fill_color);
	}
	ili9341_cs_release();
}

UINT16 ili9341_draw_text(UINT16 row, UINT16 col, const char* str)
{
	UINT16 str_base;
	UINT16 font_idx;
	UINT8 font_byte;
	UINT8 font_line;
	UINT8 font_col;	
	
	str_base = (UINT16)str;
	while((col <= (ILI9341_DA_COL_END - 8)) && *str)
	{
		if(*str == '\n')
		{
			++str;
			row += 8;
			continue;
		}
		font_idx = (*str++) << 3;
		
		ili9341_set_gram_window(row, col, 8, 8);
		col += 8;
		
		ili9341_enter_data_mode();
		ili9341_cs_assert();
		for(font_line = 0; font_line < 8; ++font_line)
		{
			font_byte = ili9341_8x8_font[font_idx++];
			for(font_col = 0; font_col < 8; ++font_col)
			{
				if(font_byte & 0x80)
				{
					(void)spi_transfer((UINT8)(ili9341_text_fg_color >> 8));
					(void)spi_transfer((UINT8)ili9341_text_fg_color);
				}
				else
				{
					(void)spi_transfer((UINT8)(ili9341_text_bg_color >> 8));
					(void)spi_transfer((UINT8)ili9341_text_bg_color);
				}
				font_byte = font_byte << 1;
			}
		}
		ili9341_cs_release();
	}
	return (UINT16)str - str_base;
}

